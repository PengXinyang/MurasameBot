from __future__ import annotations

from collections.abc import Callable, Mapping, Sequence
from contextlib import AbstractContextManager
from typing import Any, Protocol

from murasamebot.domain.models import Action, Artwork, ContentRef, Document, Emoji, Event, ImageInput, ImageRef, PrivateInbox, Receipt, PublicationCheck


class ModelGateway(Protocol):
    def decide(self, operation: str, payload: Mapping[str, Any]) -> dict[str, Any]: ...


class OwnerObservationSource(Protocol):
    def authorization(self, binding: dict | None) -> str: ...
    def read_history(self, binding: dict, *, pages: int, since: float) -> tuple[list[dict], str]: ...


class OwnerObservationStore(Protocol):
    def observation_diary_batch(self, person_id: str, now: float, cutoff: float, retention_days: int, limit: int) -> list[dict]: ...
    def owner_history_sources(self, person_id: str, source_ids: tuple[str, ...], now: float, retention_days: int) -> list[dict[str, Any]]: ...
    def get_setting(self, key: str, default: Any = None) -> Any: ...
    def set_setting(self, key: str, value: Any) -> None: ...
    def has_action_for_content(self, key: str, now: float) -> bool: ...
    def binding(self, person_id: str, platform: str) -> dict | None: ...
    def acquire_lease(self, key: str, now: float, seconds: float) -> bool: ...
    def release_lease(self, key: str) -> None: ...
    def owner_history_state(self, person_id: str) -> dict: ...
    def owner_history_status(self, person_id: str, revision: str, patch: dict) -> bool: ...
    def owner_history_commit(self, person_id: str, binding: dict, revision: str, auth: str,
                             rows: list[dict], warning: str, now: float, retention_days: int) -> bool: ...
    def owner_history_rows(self, person_id: str, now: float, *, limit: int = 30,
                           since: float = 0, eligible_only: bool = False) -> list[dict]: ...


class MemoryRepository(Protocol):
    """Scoped archive, derived products and atomic maintenance checkpoints."""
    def observation_diary_commit(self, context: dict, text: str, epoch: int, now: float, retention_days: int) -> bool: ...
    def get_setting(self, key: str, default: Any = None) -> Any: ...
    def set_setting(self, key: str, value: Any) -> None: ...
    def memory(self, person_id: str, scope: str, purpose: str, now: float, *, limit: int = 8, query: str = "") -> list[dict[str, Any]]: ...
    def memory_records(self, person_id: str, scope: str, purpose: str, *, query: str = "", limit: int = 20, before: float | None = None) -> list[dict[str, Any]]: ...
    def memory_products(self, person_id: str, scope: str, purpose: str, *, limit: int = 20, query: str = "") -> list[dict[str, Any]]: ...
    def memory_corrections(self, source_ids: list[str]) -> list[dict[str, Any]]: ...
    def memory_backfill(self, limit: int = 200) -> None: ...
    def memory_recover_jobs(self, now: float) -> None: ...
    def memory_source_records(self, source_ids: list[str]) -> list[dict[str, Any]]: ...
    def memory_batch(self, kind: str, *, cutoff: float, batch_size: int, min_messages: int, recent: int = 0, min_characters: int = 0) -> list[dict[str, Any]]: ...
    def memory_reserve(self, day: str, limit: int) -> bool: ...
    def memory_job(self, job_id: str, kind: str, state: str, now: float, detail: str = "") -> None: ...
    def memory_commit(self, records: list[dict[str, Any]], products: list[dict[str, Any]], kind: str, epoch: int, now: float) -> bool: ...
    def acquire_lease(self, name: str, now: float, duration: float) -> bool: ...
    def release_lease(self, name: str) -> None: ...


class EmojiCatalog(Protocol):
    def emoji_options(self, account_id: str, channel: str) -> Sequence[Emoji]: ...


class ImageReader(Protocol):
    def batch(self, max_bytes: int) -> AbstractContextManager: ...
    def load(self, ref: ImageRef, max_bytes: int) -> ImageInput: ...


class ContentProvider(Protocol):
    def read(self, ref: ContentRef, *, reply_to: str = "", root: str = "", context: ContentRef | None = None) -> Document: ...
    def discover(self, category_ids: Sequence[str], limit: int) -> list[ContentRef]: ...
    def search(self, query: str, category_ids: Sequence[str], limit: int) -> list[ContentRef]: ...


class ActionSink(Protocol):
    def send(self, action: Action, mentions: Mapping[str, str], *, before_write: Callable[[], bool] | None = None) -> Receipt: ...


class PublicationProbe(Protocol):
    def check_publication(self, action: Action, external_id: str) -> PublicationCheck: ...


class ArtworkSource(Protocol):
    def search_artworks(self, keyword: str, limit: int) -> list[Artwork]: ...


class EventSource(Protocol):
    def notifications(self, now: float) -> list[Event]: ...
    def owner_content(self, owner_external_id: str, now: float) -> list[Event]: ...


class PrivateMessageAccess(Protocol):
    def private_conversation(self, account_id: str, peer_id: str) -> str: ...
    def allows_private_reply(self, account_id: str, peer_id: str) -> bool: ...


class PrivateMessageSource(Protocol):
    def private_messages(self, now: float, *, since: float, cursors: Mapping[str, int], baseline: bool = False) -> PrivateInbox: ...


class SocialRepository(Protocol):
    def social_rows(self, now: float, *, limit: int = 100, include_inactive: bool = False) -> list[dict]: ...
    def social_pending(self, state_id: str) -> bool: ...
    def social_commit(self, source_id: str, source: dict, state: dict, candidates: dict, resolve: list,
                      create: bool, public_allowed: bool, now: float, ttl_hours: int, retention_days: int,
                      max_active: int, delay: int, epoch: int, owner: bool) -> dict: ...
    def social_forget(self, state_id: str, *, reason: str = "forgotten", resolve: bool = False) -> None: ...
    def social_validate(self, action: Action, now: float) -> str: ...
    def social_sources(self, refs: tuple) -> list[dict]: ...
    def social_action_context(self, action: Action) -> dict: ...


class StateStore(SocialRepository, Protocol):
    def defer_action(self, action_id: str, retry_at: float, reason: str) -> None: ...
    """Application-facing repository port; implementations own SQL and transactions."""

    def get_setting(self, key: str, default: Any = None) -> Any: ...
    def set_setting(self, key: str, value: Any) -> None: ...
    def bind(self, person_id: str, platform: str, external_id: str, display_name: str = "", purpose: str = "owner_video_recommendation") -> None: ...
    def resolve_person(self, platform: str, external_id: str) -> str | None: ...
    def binding(self, person_id: str, platform: str) -> dict[str, Any] | None: ...
    def revoke_binding(self, person_id: str, platform: str) -> None: ...
    def enqueue_event(self, event: Event, *, baseline: bool = False) -> bool: ...
    def claim_event(self, now: float) -> Event | None: ...
    def finish_event(self, event_id: str, state: str, reason: str = "") -> None: ...
    def event(self, event_id: str) -> Event | None: ...
    def retry_event(self, event_id: str, now: float, reason: str, max_attempts: int, *, delay_seconds: int = 60) -> None: ...
    def memory(self, person_id: str, scope: str, purpose: str, now: float, *, limit: int = 8, query: str = "") -> list[dict[str, Any]]: ...
    def add_memory(self, person_id: str, scope: str, purpose: str, text: str, event_id: str, now: float, *, kind: str = "preference", valid_until: float | None = None) -> str: ...
    def forget(self, memory_id: str) -> None: ...
    def add_task(self, person_id: str, topic: str, event_id: str, memory_id: str, now: float, due_at: float, expires_at: float, binding_version: int, *, target_platform: str, interval_days: int = 0, sensitive: bool = False) -> str: ...
    def active_tasks(self, person_id: str) -> list[dict[str, Any]]: ...
    def cancel_task(self, task_id: str) -> None: ...
    def claim_task(self, now: float) -> dict[str, Any] | None: ...
    def task(self, task_id: str) -> dict[str, Any] | None: ...
    def defer_task(self, task_id: str, due_at: float, reason: str, *, exhausted: bool = False) -> None: ...
    def has_action_for_content(self, content_key: str, now: float) -> bool: ...
    def enqueue_action(self, action: Action, *, draft: bool, now: float) -> bool: ...
    def claim_action(self, now: float, daily_limit: int, daily_recommendations: int, day_start: float, min_gap: float, recommendation_gap: float, allow_proactive: bool = True, manual_only: bool = False, require_review: bool = False, required_review_method: str = "", autonomous_kinds: tuple[str, ...] = ()) -> Action | None: ...
    def autonomy_snapshot(self, kind: str, now: float, start: float, exclude: str = "") -> dict[str, Any]: ...
    def autonomy_text_exists(self, kind: str, text: str) -> bool: ...
    def autonomy_recent_public(self) -> list[dict[str, Any]]: ...
    def private_activity(self, conversation: str) -> dict[str, Any]: ...
    def cancel_autonomy(self) -> None: ...
    def claim_review_action(self, now: float, *, strategy: str = "independent") -> Action | None: ...
    def validate_action(self, action: Action, now: float) -> str: ...
    def finish_action(self, action_id: str, receipt: Receipt, now: float) -> None: ...
    def publication_target(self, action_id: str) -> tuple[Action, str]: ...
    def record_publication_check(self, action_id: str, external_id: str, report: PublicationCheck) -> None: ...
    def record_action_review(self, action_id: str, state: str, reason: str, now: float, *, method: str = "independent") -> None: ...
    def approve_action(self, action_id: str, now: float) -> None: ...
    def manual_send_target(self, action_id: str) -> Action: ...
    def requeue_action(self, original: Action, action: Action, now: float, min_gap: float) -> Action: ...
    def context_history(self, conversation_id: str, *, limit: int = 6) -> list[dict[str, Any]]: ...
    def cache_document(self, document: Document, now: float) -> None: ...
    def cached_document(self, ref: ContentRef, now: float) -> Document | None: ...
    def has_viewed(self, ref: ContentRef, now: float) -> bool: ...
    def record_view(self, ref: ContentRef, reason: str, now: float) -> None: ...
    def acquire_lease(self, name: str, now: float, duration: float) -> bool: ...
    def release_lease(self, name: str) -> None: ...
    def reserve_model_call(self, day: str, limit: int) -> None: ...
    def model_usage(self, operation: str, model: str, tokens_in: int, tokens_out: int, now: float) -> None: ...
    def audit(self, kind: str, detail: str, now: float) -> None: ...
    def inspect(self, table: str, limit: int = 100) -> list[dict[str, Any]]: ...
