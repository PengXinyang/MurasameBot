from __future__ import annotations

from collections.abc import Callable, Mapping, Sequence
from contextlib import AbstractContextManager
from typing import Any, Protocol

from murasamebot.domain.models import Action, Artwork, ContentRef, Document, Event, Receipt


class ModelGateway(Protocol):
    def decide(self, operation: str, payload: Mapping[str, Any]) -> dict[str, Any]: ...


class ContentProvider(Protocol):
    def read(self, ref: ContentRef, *, reply_to: str = "", root: str = "") -> Document: ...
    def discover(self, category_ids: Sequence[str], limit: int) -> list[ContentRef]: ...
    def search(self, query: str, category_ids: Sequence[str], limit: int) -> list[ContentRef]: ...


class ActionSink(Protocol):
    def send(self, action: Action, mentions: Mapping[str, str], *, before_write: Callable[[], bool] | None = None) -> Receipt: ...


class ArtworkSource(Protocol):
    def search_artworks(self, keyword: str, limit: int) -> list[Artwork]: ...


class EventSource(Protocol):
    def notifications(self, now: float) -> list[Event]: ...
    def owner_content(self, owner_external_id: str, now: float) -> list[Event]: ...


class StateStore(Protocol):
    """Application-facing repository port; implementations own SQL and transactions."""

    def get_setting(self, key: str, default: Any = None) -> Any: ...
    def set_setting(self, key: str, value: Any) -> None: ...
    def bind(self, person_id: str, platform: str, external_id: str, display_name: str = "", purpose: str = "owner_video_recommendation") -> None: ...
    def resolve_person(self, platform: str, external_id: str) -> str | None: ...
    def binding(self, person_id: str, platform: str) -> dict[str, Any] | None: ...
    def revoke_binding(self, person_id: str, platform: str) -> None: ...
    def enqueue_event(self, event: Event, *, baseline: bool = False) -> bool: ...
    def claim_event(self, now: float) -> Event | None: ...
    def finish_event(self, event_id: str, state: str, reason: str = "") -> None: ...
    def retry_event(self, event_id: str, now: float, reason: str, max_attempts: int) -> None: ...
    def memory(self, person_id: str, scope: str, purpose: str, now: float, *, limit: int = 8) -> list[dict[str, Any]]: ...
    def add_memory(self, person_id: str, scope: str, purpose: str, text: str, event_id: str, now: float, *, kind: str = "preference", valid_until: float | None = None) -> str: ...
    def forget(self, memory_id: str) -> None: ...
    def add_task(self, person_id: str, topic: str, event_id: str, memory_id: str, now: float, due_at: float, expires_at: float, binding_version: int, *, target_platform: str, interval_days: int = 0, sensitive: bool = False) -> str: ...
    def active_tasks(self, person_id: str) -> list[dict[str, Any]]: ...
    def cancel_task(self, task_id: str) -> None: ...
    def claim_task(self, now: float) -> dict[str, Any] | None: ...
    def task(self, task_id: str) -> dict[str, Any] | None: ...
    def defer_task(self, task_id: str, due_at: float, reason: str, *, exhausted: bool = False) -> None: ...
    def has_action_for_content(self, content_key: str, now: float) -> bool: ...
    def enqueue_action(self, action: Action, *, draft: bool, now: float) -> bool: ...
    def claim_action(self, now: float, daily_limit: int, daily_recommendations: int, day_start: float, min_gap: float, recommendation_gap: float, allow_proactive: bool = True, manual_only: bool = False) -> Action | None: ...
    def validate_action(self, action: Action, now: float) -> str: ...
    def finish_action(self, action_id: str, receipt: Receipt, now: float) -> None: ...
    def approve_action(self, action_id: str, now: float) -> None: ...
    def context_history(self, conversation_id: str, *, limit: int = 6) -> list[dict[str, Any]]: ...
    def cache_document(self, document: Document, now: float) -> None: ...
    def cached_document(self, ref: ContentRef, now: float) -> Document | None: ...
    def has_viewed(self, ref: ContentRef, now: float) -> bool: ...
    def record_view(self, ref: ContentRef, reason: str, now: float) -> None: ...
    def acquire_lease(self, name: str, now: float, duration: float) -> bool: ...
    def release_lease(self, name: str) -> None: ...
    def reserve_model_call(self, day: str, limit: int) -> None: ...
    def model_usage(self, operation: str, model: str, tokens_in: int, tokens_out: int, now: float) -> None: ...
    def audit(self, kind: str, detail: str, now: float) -> None: ...
    def inspect(self, table: str, limit: int = 100) -> list[dict[str, Any]]: ...
